
-- 创建teacher表

DROP TABLE IF EXISTS t_teachers;

CREATE TABLE t_teachers(
	t_id INT PRIMARY KEY AUTO_INCREMENT,
	t_name VARCHAR(20) un`t_emp`,
	t_age INT DEFAULT 18,
	t_gender CHAR(2),
	CHECK(t_gender IN ('男','女'))	
)

