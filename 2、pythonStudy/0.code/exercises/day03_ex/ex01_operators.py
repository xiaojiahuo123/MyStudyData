# ----- 题11: 位运算深入 - 负数的表示 -----
# Python 的整数是任意精度的，没有固定位数
# 但理解补码对位运算很重要
num = -12
print(f"-12 的二进制(bin): {bin(num)}")
# Python 的 bin() 对负数会显示 -0b 前缀

# 在固定8位系统中，-12 的补码是 11110100
# Python 没有位数限制，所以 -12 的二进制理论上是 ...11110100 (无限个1)

# 验证: ~x == -(x+1)  (按位取反)
print(f"~12 = {~12}")      # ____
print(f"~(-12) = {~(-12)}") # ____
print(f"~0 = {~0}")        # ____
