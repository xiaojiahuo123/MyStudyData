# ----- 题5: 逻辑运算的短路与返回值 -----
# and 和 or 返回的是操作数本身，不是 True/False
# 短路规则:
# - and: 第一个为假，直接返回第一个；否则返回第二个
# - or:  第一个为真，直接返回第一个；否则返回第二个

print(f"0 and 5:    {0 and 5}")      # ____0   0 and 5 的结果是 0，不是 False。and/or 返回的是操作数本身，不是布尔值
print(f"3 and 5:    {3 and 5}")      # ____5
print(f"0 or 5:     {0 or 5}")       # ____5
print(f"3 or 5:     {3 or 5}")       # ____3
print(f"'' and 'hi': {'' and 'hi'}") # ____''空格
print(f"'hi' or '':  {'hi' or ''}")  # ____hi

# 实际应用: 设置默认值
username = "" or "匿名用户"
print(f"用户名: {username}")  # ____

