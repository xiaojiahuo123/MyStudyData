# ----- 题9: 运算符优先级 -----
# 不运行代码，预测以下表达式的结果
print(f"2 + 3 * 4: {2 + 3 * 4}")           # ____
print(f"(2 + 3) * 4: {(2 + 3) * 4}")       # ____
print(f"2 ** 3 ** 2: {2 ** 3 ** 2}")        # ____  注意: ** 是右结合的！
print(f"(2 ** 3) ** 2: {(2 ** 3) ** 2}")    # ____
print(f"-2 ** 2: {-2 ** 2}")                # ____  注意: - 比 ** 优先级低
print(f"(-2) ** 2: {(-2) ** 2}")            # ____

# 优先级记忆口诀:
# 算术 > 比较 > 逻辑 > 赋值
# ** > * / // % > + -


# ----- 题10: 海象运算符 (:=) -----
# Python 3.8+ 引入，可以在表达式中赋值
import random

# 传统写法
n = random.randint(1, 100)
if n > 50:
    print(f"{n} 大于 50")

# 海象运算符写法
