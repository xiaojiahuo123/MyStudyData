# ----- 题10: 海象运算符 (:=) -----
# Python 3.8+ 引入，可以在表达式中赋值
import random

# 传统写法
n = random.randint(1, 100)
if n > 50:
    print(f"{n} 大于 50")

# 海象运算符写法
if (n := random.randint(1, 100)) > 50:
    print(f"{n} 大于 50")

